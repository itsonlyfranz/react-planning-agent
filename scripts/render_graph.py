"""Regenerate the agent flow diagram embedded in README.md.

The diagram is rendered from the real compiled LangGraph graph, so it cannot silently drift
from the code. Fully offline: the agent is built with a scripted LLM and never calls a model.

    python scripts/render_graph.py   # rewrite the block in README.md
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from react_agent import ReActAgent
from react_agent.fake import ScriptedLLM

README = ROOT / "README.md"
BEGIN = "<!-- flow-diagram:begin (generated by scripts/render_graph.py) -->"
END = "<!-- flow-diagram:end -->"
BLOCK = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)


def render_mermaid() -> str:
    return ReActAgent(ScriptedLLM([])).graph.get_graph().draw_mermaid().strip()


def render_block() -> str:
    return f"{BEGIN}\n```mermaid\n{render_mermaid()}\n```\n{END}"


def updated_readme(text: str) -> str:
    if not BLOCK.search(text):
        raise SystemExit(f"README.md is missing the {BEGIN!r} ... {END!r} markers")
    return BLOCK.sub(lambda _: render_block(), text, count=1)


def main() -> int:
    README.write_text(updated_readme(README.read_text()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
